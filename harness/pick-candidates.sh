#!/bin/bash
# Regenerate harness/candidates.txt from the device's own repo indexes.
#
#   ./harness/pick-candidates.sh [count]     # default 25
#
# Harness candidates are SINGLE-USE: a run converts its package and leaves the
# result in /var/mobile/RootHidePatcher/, which rhdarchived serves as a local
# Sileo repo on :8140, after which Sileo finds a roothide build and never raises
# "Not Updated" for it again. So the pool needs topping up periodically — this
# script does it from the machine that knows the truth, the phone.
#
# A candidate must be:
#   * Architecture: iphoneos-arm64      (arm64e is already roothide-native)
#   * not installed                     (installed => the button reads Modify)
#   * not served by the local :8140 repo (already converted at some point)
#   * not already burned this session
#   * not matched by patch.sh's INCOMPATIBLE_PACKAGES substrings
#   * small, so the download is instant — sorted by Size, smallest first
#
# Nothing is ever installed by a harness run: the flow stops at Sileo's queue
# confirm screen.

set -uo pipefail
cd "$(dirname "$0")/.."

DEVICE="${DEVICE:-ip14}"
COUNT="${1:-25}"
LOCAL_INDEX='/var/lib/apt/lists/127.0.0.1:8140_._Packages'
OUT=harness/candidates.txt

PASS=$(security find-generic-password -s trollstore -a "$DEVICE" -w)

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

echo "==> reading repo indexes from $DEVICE"
# Package + Size for every arm64 entry, excluding the local converted-deb repo.
#
# Two entries are dropped here because patch.sh refuses them and the refusal
# looks exactly like a tweak failure in the log:
#   * Maintainer "Procursus Team" — patch.sh exits with "Not a tweak package!"
#   * Size 0 or absent — a malformed index entry, and unsortable by size
ssh "$DEVICE" 'for f in /var/lib/apt/lists/*_Packages; do
	case "$f" in *8140*) continue;; esac
	awk -v RS="" -F"\n" "{p=\"\";a=\"\";s=0;m=\"\";
		for(i=1;i<=NF;i++){
			if(\$i ~ /^Package: /){p=substr(\$i,10)}
			if(\$i ~ /^Architecture: /){a=substr(\$i,15)}
			if(\$i ~ /^Size: /){s=substr(\$i,7)+0}
			if(\$i ~ /^Maintainer: /){m=substr(\$i,13)}
		}
		if(a==\"iphoneos-arm64\" && p!=\"\" && s>0 && m !~ /Procursus/) print s\" \"p}" "$f"
done' 2>/dev/null | tr -d '\r' | grep -v '^$' | sort -k2,2 -u > "$TMP/pool"

ssh "$DEVICE" "echo '$PASS' | sudo -S -p '' /var/jb/usr/bin/dpkg-query -W -f='\${Package}\n'" 2>/dev/null \
	| tr -d '\r' | grep -v '^$' | sort -u > "$TMP/installed"

ssh "$DEVICE" "grep '^Package: ' '$LOCAL_INDEX' 2>/dev/null | sed 's/^Package: //'" 2>/dev/null \
	| tr -d '\r' | grep -v '^$' | sort -u > "$TMP/served"

touch harness/.burned
cat "$TMP/installed" "$TMP/served" harness/.burned | sort -u > "$TMP/exclude"

echo "    arm64 in repos: $(wc -l < "$TMP/pool" | tr -d ' ')"
echo "    excluded (installed / already converted / burned): $(wc -l < "$TMP/exclude" | tr -d ' ')"

# patch.sh's INCOMPATIBLE_PACKAGES — matched as substrings of the package id,
# exactly as patch.sh does it. Kept in sync with
# /var/jb/Applications/Patcher.app/patch.sh.
BLOCK='xinam1ne|xinamine|legizmo|vnodebypass|voicechangerx-rootless|appsyncunified|choicy|com\.tigisoftware\.filza|sileo|zebra|com\.opa334\.ccsupport|ws\.hbang\.common|libsandy|preferenceloader|newterm3|altlist|ellekit|oldabi'

# Set difference via join rather than a giant alternation regex — hundreds of
# exclusions would otherwise be one unreadable, ARG_MAX-sized pattern.
awk '{print $2" "$1}' "$TMP/pool" | sort -u > "$TMP/bypkg"
join -v1 "$TMP/bypkg" "$TMP/exclude" 2>/dev/null > "$TMP/kept"

# Smallest first, but at most 2 per vendor prefix. Without the cap a single
# publisher with 40 near-identical packages fills the whole list, and the pool
# stops being a varied sample of what actually needs converting.
grep -vE "$BLOCK" "$TMP/kept" | sort -k2,2n | awk '
	{
		n = split($1, parts, ".")
		vendor = (n >= 2) ? parts[1] "." parts[2] : $1
		if (++seen[vendor] <= 2) print $1
	}' | head -n "$COUNT" > "$TMP/picked"

PICKED=$(wc -l < "$TMP/picked" | tr -d ' ')
if [ "$PICKED" -eq 0 ]; then
	echo "no usable candidates found — is the device's apt cache populated?"
	exit 1
fi

{
	echo "# Test packages for harness/run.sh — regenerated by harness/pick-candidates.sh."
	echo "#"
	echo "# Criteria: Architecture: iphoneos-arm64 (so Sileo raises \"Not Updated\"),"
	echo "# not installed, not already served by the local :8140 repo, not on"
	echo "# patch.sh's INCOMPATIBLE_PACKAGES list, smallest downloads first."
	echo "#"
	echo "# CANDIDATES ARE SINGLE-USE. A run leaves its converted deb in"
	echo "# /var/mobile/RootHidePatcher/, the local repo then serves a roothide build,"
	echo "# and Sileo stops raising \"Not Updated\" for it. Re-run this script to top up."
	echo "#"
	echo "# Nothing is ever installed by a run — the flow stops at the confirm screen."
	echo
	cat "$TMP/picked"
} > "$OUT"

echo "==> wrote $PICKED candidates to $OUT"
head -5 "$TMP/picked" | sed 's/^/    /'
